"""Shared state schema for the YAML Repair multi-agent system."""

from typing import Literal, TypedDict


class RepairState(TypedDict):
    """State dict passed through the repair workflow graph.

    Populated incrementally by each agent in the workflow.
    """

    # ── Input from the Supervisor ─────────────────────────────────────────────
    automation_id: str
    """The Home Assistant automation entity_id that failed (e.g., 'automation.my_automation')."""

    error: str
    """The raw error message or failure signal from Home Assistant."""

    # ── Populated by DiagnosticsAgent ─────────────────────────────────────────
    yaml_content: str
    """The raw YAML source of the failing automation, fetched from Home Assistant."""

    error_logs: list[str]
    """Recent error log entries from Home Assistant mentioning this automation."""

    known_entity_ids: list[str]
    """All entity_ids currently available in Home Assistant (used for stale reference detection)."""

    # ── Populated by RootCauseAgent ───────────────────────────────────────────
    root_cause: str
    """LLM-generated diagnosis of why the automation failed (one concise paragraph)."""

    stale_entities: list[str]
    """Entity references present in the YAML but not in Home Assistant's live entity list."""

    # ── Populated by YAMLRepairAgent ──────────────────────────────────────────
    repaired_yaml: str
    """The corrected automation YAML generated by the LLM."""

    repair_notes: str
    """Human-readable notes from the LLM about what was changed and why."""

    # ── Populated by ValidatorAgent ───────────────────────────────────────────
    validation_ok: bool
    """Whether the repaired YAML passed validation (local + HA dry-run checks)."""

    validation_error: str
    """Error message if validation failed; empty string if validation_ok is True."""

    # ── Loop control ──────────────────────────────────────────────────────────
    repair_attempts: int
    """Number of repair attempts made so far; incremented after each repair node."""

    # ── Final outcome ─────────────────────────────────────────────────────────
    status: Literal["deployed", "escalated", "failed"]
    """Final status of the repair: 'deployed' (success), 'escalated' (max retries), or 'failed'."""

    summary: str
    """Human-readable summary of the repair outcome, including root cause and repair notes."""
